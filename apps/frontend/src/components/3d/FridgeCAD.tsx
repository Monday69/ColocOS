function InteractiveZone({
  zoneId,
  status,
  geometry,
  material,
  position,
  onZoneSelect,
  interactive = true,
  visible = true,
}: InteractiveZoneProps) {
  const [hovered, setHovered] = useState(false)
  const meshRef = useRef<THREE.Mesh>(null)

  const zoneMaterial = useMemo(() => material.clone(), [material])
  useEffect(() => () => zoneMaterial.dispose(), [zoneMaterial])

  // Enregistrement dans le registre (cadrage caméra sur bornes réelles)
  useEffect(() => {
    const mesh = meshRef.current
    if (!mesh) return
    return registerZoneObject(zoneId, mesh)
  }, [zoneId])

  // État CAD d'origine — restauré quand la zone est vide
  const baseEmissive = useMemo(() => zoneMaterial.emissive.clone(), [zoneMaterial])
  const baseIntensity = zoneMaterial.emissiveIntensity ?? 0

  const statusHex = ZONE_HEALTH_EMISSIVE[status]
  const targetColor = useMemo(
    () => (statusHex ? new THREE.Color(statusHex) : baseEmissive.clone()),
    [statusHex, baseEmissive],
  )

  const targetIntensity =
    statusHex === null
      ? baseIntensity
      : ZONE_HEALTH_INTENSITY[status] * (hovered ? HOVER_INTENSITY_MULTIPLIER : 1)

  useFrame((_, delta) => {
    const step = Math.min(delta * 8, 1)
    zoneMaterial.emissive.lerp(targetColor, step)
    zoneMaterial.emissiveIntensity = THREE.MathUtils.damp(
      zoneMaterial.emissiveIntensity,
      targetIntensity,
      10,
      delta,
    )
  })

  return (
    <mesh
      ref={meshRef}
      geometry={geometry}
      material={zoneMaterial}
      position={position}
      // Zone non sélectionnable (porte fermée ou pendant l'animation) :
      // on n'écrase `raycast` que dans ce cas — passer `undefined` casserait
      // la méthode par défaut de THREE.Mesh et casserait tout le picking.
      visible={visible}
      {...(interactive ? {} : { raycast: NOOP_RAYCAST })}
      onPointerOver={(e) => {
        e.stopPropagation()
        setHovered(true)
        document.body.style.cursor = 'pointer'
      }}
      onPointerOut={() => {
        setHovered(false)
        document.body.style.cursor = 'default'
      }}
      onClick={(e) => {
        // Empêche le toggle de porte du groupe parent (et tout handler ancêtre)
        e.stopPropagation()
        if (!interactive) return
        onZoneSelect(zoneId)
      }}
    />
  )
}

